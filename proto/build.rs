use std::{
    collections::BTreeMap,
    fs,
    io::{self, BufRead},
    path::Path,
};

pub fn main() {
    let proto_file = "StarRail.proto";
    if std::path::Path::new(proto_file).exists() {
        println!("cargo:rerun-if-changed={proto_file}");

        prost_build::Config::new()
            .out_dir("out/")
            .type_attribute(".", "#[derive(proto_derive::CmdID)]")
            .compile_protos(&[proto_file], &["."])
            .unwrap();

        impl_message_id(Path::new("out/_.rs")).unwrap();
    }
}

pub fn impl_message_id(path: &Path) -> io::Result<()> {
    let file = fs::File::open(path)?;
    let reader = io::BufReader::new(file);
    let mut output = Vec::new();

    let mut attr = None;
    // CmdID waiting for the name of the struct it belongs to, and every message's CmdID
    let mut pending_id = None;
    let mut cmd_ids = BTreeMap::new();
    for line in reader.lines() {
        let line = line?;

        if line.contains("CmdID:") {
            let id = cmd_id(&line).unwrap();
            attr = Some(format!("#[cmdid({id})]"));
            pending_id = Some(id);
        } else {
            if let (Some(id), Some(name)) = (pending_id, struct_name(&line)) {
                cmd_ids.insert(name.to_string(), id);
                pending_id = None;
            }
            output.push(line);
            if let Some(attr) = attr.take() {
                output.push(attr);
            }
        }
    }

    output.push(request_response_pairs(&cmd_ids));
    fs::write(path, output.join("\n").as_bytes())?;
    Ok(())
}

fn cmd_id(line: &str) -> Option<u16> {
    line.trim_start().split(' ').nth(2)?.parse::<u16>().ok()
}

fn struct_name(line: &str) -> Option<&str> {
    let rest = line.trim_start().strip_prefix("pub struct ")?;
    rest.split([' ', '{']).next()
}

/// Every XxxCsReq/XxxScRsp pair that both have a CmdID, as a table the server uses to answer
/// requests it has no handler for (see `response_for` in lib.rs).
fn request_response_pairs(cmd_ids: &BTreeMap<String, u16>) -> String {
    let mut pairs: Vec<(u16, u16, &str)> = cmd_ids
        .iter()
        .filter_map(|(name, request)| {
            let base = name.strip_suffix("CsReq")?;
            let response = cmd_ids.get(&format!("{base}ScRsp"))?;
            Some((*request, *response, base))
        })
        .collect();
    pairs.sort();

    let mut table = String::from(
        "/// (request CmdID, response CmdID, name without CsReq/ScRsp) of every request/response\n\
         /// pair in StarRail.proto, sorted by request CmdID. Generated by build.rs.\n\
         pub static REQUEST_RESPONSE_PAIRS: &[(u16, u16, &str)] = &[\n",
    );
    for (request, response, name) in pairs {
        table += &format!("    ({request}, {response}, \"{name}\"),\n");
    }
    table += "];\n";
    table
}
