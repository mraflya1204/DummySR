/// Response ID and message name for a request ID, if the table has it.
pub fn response_for(request_id: u16) -> Option<(u16, &'static str)> {
    RESPONSES
        .binary_search_by_key(&request_id, |(request, _, _)| *request)
        .ok()
        .map(|i| (RESPONSES[i].1, RESPONSES[i].2))
}
